"""Build the c2 configs (2026-10-08). One change per run vs the ft_prec (ON) / b3_ft_v10c (OFF) recipes.

c1 result: lower target entropy does NOT fix reached-not-held — at -21 the policy meets the target by saturating
transit actions (log-prob 8.7 vs 2.7), hold std only 0.49→0.34 and the hold mean bias grows (|a| 0.18-0.23 vs
0.13-0.18); 3.0M held: -7 309/279, -14 313/279 & 298/247, -21 226/216 & 304/262, -28 202/172 → stopped te21/te28/off_te21.
So the bias is per-network approximation variance (what action ensembles and weight averaging remove). Phase 0:
cross-run shield-off ensembles are the strongest models (ens_off_mix6 fresh OFF 775/800 held, 7 coll).
c2_lr3e5  : learning_rate 1e-4 → 3e-5 (less SGD noise; v12_lr3e5 only ever ran from a collapsed start)
c2_bs2048 : batch_size 512 → 2048 (less critic/actor gradient noise)
c2_off_s2/s3 : b3_ft_v10c replicas, new seeds → shield-off ensemble members
"""
import copy, yaml
ON = yaml.safe_load(open('franka_sim/models/sac_v11_ft_prec/config.yaml'))
OFF = yaml.safe_load(open('franka_sim/models/sac_b3_ft_v10c/config.yaml'))
variants = {
    'c2_lr3e5':  (ON,  {'seed': 41, 'learning_rate': 3e-5}, 'learning_rate 3e-5'),
    'c2_bs2048': (ON,  {'seed': 42, 'batch_size': 2048},    'batch_size 2048'),
    'c2_off_s2': (OFF, {'seed': 43},                        'b3_ft_v10c replica (obstacle CBF OFF), seed 43'),
    'c2_off_s3': (OFF, {'seed': 44},                        'b3_ft_v10c replica (obstacle CBF OFF), seed 44'),
}
for name, (base, over, what) in variants.items():
    c = copy.deepcopy(base); c['rl'].update(over)
    src = 'sac_v11_ft_prec' if base is ON else 'sac_b3_ft_v10c'
    with open(f'franka_sim/config_{name}.yaml', 'w') as f:
        f.write(f'# sac_{name} — generated by runs/eval_all/c2/mk_c2.py from models/{src}/config.yaml (2026-10-08).\n'
                f'# Variant: {what}\n')
        yaml.safe_dump(c, f, sort_keys=False)
    print('wrote', f'config_{name}.yaml')
