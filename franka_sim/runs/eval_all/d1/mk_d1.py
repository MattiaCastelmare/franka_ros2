"""d1 batch (2026-10-09): policy alone (env.shield false), constraints as terminations, randomisation ON.

A  SAC fine-tunes (the handoff recipe, resumed with replay buffer), alone_action clip:
   d1_a_s1..s6   parent sac_v10c 2.5M,          seeds 101..106
   d1_a_p1..p2   parent sac_v12_prec_s3 3.75M,  seeds 111..112
B  PPO from scratch, alone_action scale: d1_ppo (train_ppo.py)

    cd franka_sim && python3 runs/eval_all/d1/mk_d1.py      → config_d1_*.yaml
"""
import copy
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
base = yaml.safe_load(open(os.path.join(SIM, 'config_c2_off_s2.yaml')))


def alone(c, action):
    c['env']['shield'] = False
    c['env']['alone_action'] = action
    c['constraints'] = dict(enabled=True, terminate=True, self_collision_margin=0.0,
                            sigma_floor=0.05, sigma_rot_scale=0.3,
                            terminate_on=['pos', 'vel', 'self_coll', 'sing', 'floor'])
    r = c['randomization']
    r['enabled'] = True
    r['latency'].update(enabled=True, mean_s=0.06, jitter_s=0.02)
    for k in ('obs_noise', 'joint_noise', 'dynamics'):
        r[k]['enabled'] = True
    return c


def write(name, c, note):
    p = os.path.join(SIM, f'config_{name}.yaml')
    with open(p, 'w') as f:
        f.write(f'# {name} — generated by runs/eval_all/d1/mk_d1.py from config_c2_off_s2.yaml (2026-10-09).\n# {note}\n')
        yaml.safe_dump(c, f, sort_keys=False)
    print(p)


for i in range(1, 7):
    c = alone(copy.deepcopy(base), 'clip'); c['rl']['seed'] = 100 + i
    write(f'd1_a_s{i}', c, f'A: SAC fine-tune of sac_v10c 2.5M, policy alone (clip), seed {100 + i}')
for i in range(1, 3):
    c = alone(copy.deepcopy(base), 'clip'); c['rl']['seed'] = 110 + i
    write(f'd1_a_p{i}', c, f'A: SAC fine-tune of sac_v12_prec_s3 3.75M, policy alone (clip), seed {110 + i}')

c = alone(copy.deepcopy(base), 'scale')
c['rl'] = dict(algo='PPO', seed=7, n_envs=14, total_timesteps=200_000_000, device='cuda',
               learning_rate=3e-4, n_steps=256, batch_size=3072, n_epochs=5, gamma=0.99,
               gae_lambda=0.95, clip_range=0.2, ent_coef=0.0, vf_coef=0.5, max_grad_norm=0.5,
               log_std_init=-0.5, net_arch=[256, 256], checkpoint_every_steps=5_000_000,
               tensorboard_log='runs/', save_path='models/')
write('d1_ppo', c, 'B: PPO from scratch, policy alone (scale), 14 CPU envs')
