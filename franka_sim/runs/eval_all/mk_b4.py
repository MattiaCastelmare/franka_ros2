"""Build the b4 configs (2026-10-06): shield-OFF fine-tunes aimed at PROPER obstacle avoidance.

Why (shield OFF, 400 held-out seeds): ft_v10c avoids collisions but dips below d_safe in 197 dyn / 269 static episodes
(potential shaping leaves the optimum at "don't touch"); the moving obstacle is partially observed (no v_obs); its
fine-tune buffer was collected with the shield (wrong dynamics near the obstacle); single policies are inconsistent.

Base = models/sac_v10c/config.yaml (all sources differ only in reward/rl) + COMMON:
  C1  obs_shaping penalty (NOT potential: it must change the optimum) ramp 0.20 m → contact, w 1; collision_step_cost 4
      ≥ worst per-step cost, so ending the episode by crashing never pays; w_prec 2 (v11 winner) for every run.
Per run: C2 env.cbf_obstacle_on_prob 0.3 (mix), C3 --buffer-mask (launcher), C4 obs.obstacle_velocity + --widen-obs.
"""
import copy, yaml
base = yaml.safe_load(open('franka_sim/models/sac_v10c/config.yaml'))
common = {
    ('env', 'cbf_obstacle_enabled'): False,
    ('reward', 'collision_penalty'): 50.0, ('reward', 'collision_step_cost'): 4.0,
    ('reward', 'terminate_on_collision'): True,
    ('reward', 'obs_shaping'): 'penalty', ('reward', 'w_obs_margin'): 1.0, ('reward', 'obs_soft_margin'): 0.20,
    ('reward', 'w_prec'): 2.0, ('reward', 'prec_scale'): 0.05,
    ('rl', 'learning_rate'): 1e-4, ('rl', 'total_timesteps'): 1_500_000,
}
MIX = {('env', 'cbf_obstacle_on_prob'): 0.3}
VOBS = {('obs', 'obstacle_velocity'): True}
FULL = {**MIX, **VOBS}
variants = {   # name: (overrides, description)  — source/mask/widen live in launch_b4.sh
    'b4_clear':      ({('rl', 'seed'): 40}, 'C1 clearance penalty only (control for 2-5), from v10c 2.5M'),
    'b4_clear_filt': ({('rl', 'seed'): 41}, 'C1 + C3 buffer mask, from v10c 2.5M'),
    'b4_clear_mix':  ({**MIX, ('rl', 'seed'): 42}, 'C1 + C2 shield mixing p_on 0.3, from v10c 2.5M'),
    'b4_clear_vobs': ({**VOBS, ('rl', 'seed'): 43}, 'C1 + C4 v_obs (27-D), from v10c 2.5M'),
    'b4_full':       ({**FULL, ('rl', 'seed'): 44}, 'C1+C2+C3+C4, from v10c 2.5M'),
    'b4_full_ps3':   ({**FULL, ('rl', 'seed'): 45}, 'full, from v12_prec_s3 3.75M (ensemble member)'),
    'b4_full_ps2':   ({**FULL, ('rl', 'seed'): 46}, 'full, from v12_prec_s2 3.75M (ensemble member)'),
    'b4_full_lr3e5': ({**FULL, ('rl', 'seed'): 47}, 'full, from v12_lr3e5 4.75M (ensemble member)'),
    'b4_full_s2':    ({**FULL, ('rl', 'seed'): 48}, 'full, from v10c 2.5M, second seed (ensemble member)'),
    'b4_full_m25':   ({**FULL, ('reward', 'obs_soft_margin'): 0.25, ('reward', 'w_obs_margin'): 2.0,
                       ('rl', 'seed'): 49}, 'full with a stronger clearance cost (ramp 0.25 m, w 2), from v10c 2.5M'),
}
for name, (over, what) in variants.items():
    c = copy.deepcopy(base)
    for (sec, key), v in {**common, **over}.items():
        c.setdefault(sec, {})[key] = v
    with open(f'franka_sim/config_{name}.yaml', 'w') as f:
        f.write(f'# sac_{name} — generated by runs/eval_all/mk_b4.py from models/sac_v10c/config.yaml (2026-10-06).\n'
                f'# Shield-OFF fine-tune for proper avoidance. Variant: {what}\n')
        yaml.safe_dump(c, f, sort_keys=False)
    print('wrote', f'config_{name}.yaml')
