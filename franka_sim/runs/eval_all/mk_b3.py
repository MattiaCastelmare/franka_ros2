"""Build the b3 configs (2026-10-05): END-TO-END RL, obstacle CBF rows OFF, on the v10 recipe.

Why: Run B (b1/b2/b2r) was built on sac_v9's failing recipe (gamma 0.997, 8 envs, 8 grad steps, 51-D obs,
touch-once success), so "end-to-end RL fails" was never tested fairly. Test 1 (noshield_summary.txt) showed the
shielded ensemble already owns moving-obstacle avoidance (8/400 coll) but leans on the shield for static obstacles
near the start (55/400). b3 asks whether the v10 recipe learns BOTH reaching and avoidance with no obstacle shield.

Base = models/sac_v10/config.yaml (v10 recipe: 24-D obs, gamma 0.99, 1 env, 1 grad step, lr 3e-4, holdable
targets, terminate_on_success false, static_fraction 0.5; joint/vel/slew/workspace/floor/base rows stay ON)
+ Run B2's reward fixes: collision ends the episode and costs collision_penalty + collision_step_cost x remaining
ticks (no early-crash hack), potential-based obstacle proximity shaping (no living cost).
Every variant changes ONE thing vs b3_base.
"""
import copy, yaml
base = yaml.safe_load(open('franka_sim/models/sac_v10/config.yaml'))
common = {
    ('env', 'cbf_obstacle_enabled'): False,
    ('reward', 'collision_penalty'): 50.0, ('reward', 'collision_step_cost'): 2.0,
    ('reward', 'terminate_on_collision'): True,
    ('reward', 'obs_shaping'): 'potential', ('reward', 'w_obs_margin'): 2.0, ('reward', 'obs_soft_margin'): 0.10,
}
variants = {
    'b3_base':     ({('rl', 'seed'): 30}, 'base'),
    'b3_base_s2':  ({('rl', 'seed'): 31}, 'base, seed 31 (replicate)'),
    'b3_base_s3':  ({('rl', 'seed'): 32}, 'base, seed 32 (replicate)'),
    'b3_margin30': ({('reward', 'obs_soft_margin'): 0.30, ('rl', 'seed'): 33}, 'shaping ramp starts at 0.30 m instead of 0.10'),
    'b3_wobs5':    ({('reward', 'w_obs_margin'): 5.0, ('rl', 'seed'): 34}, 'shaping weight 5 instead of 2'),
    'b3_coll200':  ({('reward', 'collision_penalty'): 200.0, ('rl', 'seed'): 35}, 'collision_penalty 200 instead of 50'),
    'b3_prec':     ({('reward', 'w_prec'): 2.0, ('reward', 'prec_scale'): 0.05, ('rl', 'seed'): 36}, '+ w_prec 2 (v11 winner term)'),
    'b3_obs51':    ({('obs', 'control_point_geometry'): True, ('obs', 'obstacle_velocity'): True, ('rl', 'seed'): 37},
                    '51-D obs (v_obs + per-CP d/n): link-level info, which the shield no longer supplies'),
    'b3_noterm':   ({('reward', 'terminate_on_collision'): False, ('rl', 'seed'): 38},
                    'collision does not end the episode; collision_penalty charged every tick inside the obstacle'),
    'b3_ft_v10c':  ({('rl', 'learning_rate'): 1e-4, ('rl', 'seed'): 39},
                    'FINE-TUNE of sac_v10c 2.5M (+ relabelled v10c buffer), lr 1e-4: shield-trained policy learns to avoid alone'),
}
for name, (over, what) in variants.items():
    c = copy.deepcopy(base)
    for (sec, key), v in {**common, **over}.items():
        c.setdefault(sec, {})[key] = v
    with open(f'franka_sim/config_{name}.yaml', 'w') as f:
        f.write(f'# sac_{name} — generated by runs/eval_all/mk_b3.py from models/sac_v10/config.yaml (2026-10-05).\n'
                f'# End-to-end RL: obstacle CBF rows OFF. Variant: {what}\n')
        yaml.safe_dump(c, f, sort_keys=False)
    print('wrote', f'config_{name}.yaml')
