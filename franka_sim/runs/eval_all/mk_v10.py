"""Build the three sac_v10 configs from the live config.yaml (v4 recipe + fixed task/shield)."""
import copy, yaml
base = yaml.safe_load(open('franka_sim/config.yaml'))
common = {
    # v4 recipe
    ('rl', 'gamma'): 0.99, ('rl', 'n_envs'): 1, ('rl', 'gradient_steps'): 1,
    ('reward', 'w_ws_margin'): 0.0,
    ('obs', 'control_point_geometry'): False, ('obs', 'obstacle_velocity'): False,   # 24-D obs
    # task: every target reachable AND holdable, obstacle on the path in 60 %
    ('task', 'blocking_fraction'): 0.6, ('task', 'target_clearance'): 0.26,
    ('task', 'target_free_always'): True, ('task', 'reset_max_tries'): 3000,
    # hold the target: success no longer ends the episode (w_success paid per step on target)
    ('reward', 'terminate_on_success'): False,
    # half the episodes with a static obstacle
    ('obstacle', 'static_fraction'): 0.5,
    # shield as in the test videos: floor + base keep-out + soft fallback
    ('cbf', 'floor_enable'): True, ('cbf', 'base_keepout_enable'): True, ('cbf', 'soft_fallback'): True,
}
variants = {
    'v10':       {},
    'v10_obs51': {('obs', 'control_point_geometry'): True, ('obs', 'obstacle_velocity'): True},
    'v10_g997':  {('rl', 'gamma'): 0.997},
}
header = ('# sac_{name} — generated by runs/eval_all/mk_v10.py from config.yaml (2026-09-29).\n'
          '# v4 recipe (24-D obs, gamma 0.99, 1 env, 1 grad step, no w_ws_margin) + reachable/holdable targets,\n'
          '# terminate_on_success false, static_fraction 0.5, floor + base keep-out + soft fallback in the shield.\n'
          '# Variant: {what}\n')
what = {'v10': 'baseline', 'v10_obs51': '51-D obs (v_obs + per-CP d/n)', 'v10_g997': 'gamma 0.997'}
for name, over in variants.items():
    c = copy.deepcopy(base)
    for (sec, key), v in {**common, **over}.items():
        c.setdefault(sec, {})[key] = v
    with open(f'franka_sim/config_{name}.yaml', 'w') as f:
        f.write(header.format(name=name, what=what[name]))
        yaml.safe_dump(c, f, sort_keys=False)
    print('wrote', f'config_{name}.yaml')
