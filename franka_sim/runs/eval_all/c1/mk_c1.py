"""Build the c1 configs (2026-10-08): lower SAC target entropy, everything else = the ft_prec / b3_ft_v10c recipes.

Diagnosis (runs/eval_all/c1/probe_hold.py, probe_std.py): single policies lose most episodes as
reached-not-held (ft_prec 3.75M: 55 dyn / 51 static of 400) — the deterministic action at the target has
|a| 0.1-0.3 and the arm drifts out; the 9-member ensemble averages that bias away (|a| 0.04) and holds 54/55.
Freezing the obstacle slots does not stop the drift. The SAC policy std is ~0.5 (pre-tanh) at the target
as in transit: target_entropy 'auto' = -7 is met on average by the saturated transit actions, so at the
target the policy is near-random and the mean action is never forced to be precise.
Every run = resume v10c 2.5M + relabelled v10c buffer, +1.25M (ON) / +1.5M (OFF), like ft_prec / prec_s2 / prec_s3 / b3_ft_v10c.
"""
import copy, yaml
ON = yaml.safe_load(open('franka_sim/models/sac_v11_ft_prec/config.yaml'))
OFF = yaml.safe_load(open('franka_sim/models/sac_b3_ft_v10c/config.yaml'))
variants = {
    'c1_ctrl':      (ON,  {'seed': 31},                          'ft_prec replica (control, target_entropy auto = -7)'),
    'c1_te14':      (ON,  {'seed': 32, 'target_entropy': -14.0}, 'target_entropy -14'),
    'c1_te14_s2':   (ON,  {'seed': 33, 'target_entropy': -14.0}, 'target_entropy -14, 2nd seed'),
    'c1_te21':      (ON,  {'seed': 34, 'target_entropy': -21.0}, 'target_entropy -21'),
    'c1_te21_s2':   (ON,  {'seed': 35, 'target_entropy': -21.0}, 'target_entropy -21, 2nd seed'),
    'c1_te28':      (ON,  {'seed': 36, 'target_entropy': -28.0}, 'target_entropy -28'),
    'c1_off_te21':  (OFF, {'seed': 37, 'target_entropy': -21.0}, 'b3_ft_v10c recipe (obstacle CBF OFF) + target_entropy -21'),
    'c1_off_te14':  (OFF, {'seed': 38, 'target_entropy': -14.0}, 'b3_ft_v10c recipe (obstacle CBF OFF) + target_entropy -14'),
}
for name, (base, over, what) in variants.items():
    c = copy.deepcopy(base); c['rl'].update(over)
    src = 'sac_v11_ft_prec' if base is ON else 'sac_b3_ft_v10c'
    with open(f'franka_sim/config_{name}.yaml', 'w') as f:
        f.write(f'# sac_{name} — generated by runs/eval_all/c1/mk_c1.py from models/{src}/config.yaml (2026-10-08).\n'
                f'# Variant: {what}\n')
        yaml.safe_dump(c, f, sort_keys=False)
    print('wrote', f'config_{name}.yaml')
