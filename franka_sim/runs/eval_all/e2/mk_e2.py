"""e2 batch (2026-10-20): graft the d2 nets onto the 51-D scene-agnostic observation.

What e1 taught (runs/eval_all/e1/auto_eval.log, re-read 2026-10-20)
-----------------------------------------------------------------
* From scratch, the 51-D SimBa runs needed 4M steps to find the target at all and plateaued at
  rollout success ~0.6; best checkpoint 471/800 behind the shield (a1 6.0M), the MLP control 199,
  a3 (no correction cost) never learned.
* The 24-D d2 ensemble was never run in the 2-3-sphere scenes. It does 784/800 alone and 692 behind
  the shield there (big11 683) — its single `obstacle` slot already holds the NEAREST sphere. So
  the multi-sphere task is not where the policy fails; the shield is (alone 784 vs full 692; one
  sphere 795 vs 750).
* e1's "one sphere" eval was not one sphere: eval_e1.sh used each model's own config, i.e.
  count_range [1,3] and target_ik_check true (other episodes per seed). e2/eval_e2.sh forces both.
* The control-point block was the sim's TRUE, current geometry next to a 60 ms-delayed obstacle
  slot; on the robot both come from the same MultiLinkDistance message. randomization.cp_geometry
  (new) puts dᵢ, n̂ᵢ through the same delay / noise / LPF / clamp as d_min.

Recipe
------
Parents = the 6 best d2 finals (alone, held-out nominal: p_s5 634, p4_s1 613, p_p2 606, b_1 578,
b_2 571, p4_p1 564). train.py --widen-obs grafts each 24-D net onto the 51-D layout with ZERO
weights on the 27 new inputs (same function at step 0) and rebuilds its own 1M-transition replay
buffer at 51-D (v_obs by finite difference, dᵢ/n̂ᵢ by forward kinematics, train.widen_buffer), so
there is no fresh-buffer collapse (HANDOFF §5). Then +2.0M steps policy-ALONE (the d2 recipe: the
d3 shield-in-the-loop fine-tunes became shield-dependent) in 1-3-sphere scenes, d1 randomisation +
perceived control-point block.

Arms (same 6 parents in both → paired comparison; seed = 500 + k / 510 + k):
  G  reward as the parent (potential shaping, margin 0.10 — leaves the optimal policy unchanged)
  S  "shield-compatible": per-step penalty w 1.0 below d_safe + 2 cm (obs_shaping penalty, margin
     0.17). The shield parks the hand on the d_safe shell; nothing in the d2 reward tells the policy
     where that shell is, so it approaches the way the shield blocks (d3 analysis: 36/43 shield-on
     static failures have a holding pose with every link at d >= d_safe, and the policy alone holds
     35 of them). Worst per-step cost 1 (dist) + 1 = collision_step_cost 2, so crashing never pays.
     The buffer rewards are relabelled from the parent's config (train.relabel_buffer).

    cd franka_sim && python3 runs/eval_all/e2/mk_e2.py      → config_e2_*.yaml
"""
import copy
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.abspath(os.path.join(HERE, '..', '..', '..'))

PARENTS = ['p_s5', 'p4_s1', 'p_p2', 'b_1', 'b_2', 'p4_p1']
ARMS = {
    'g': (500, 'graft 24->51-D, parent reward'),
    's': (510, 'graft 24->51-D + per-step penalty below d_safe + 2 cm (w 1.0, margin 0.17)'),
}


def make(arm, parent, seed):
    c = yaml.safe_load(open(os.path.join(SIM, 'models', f'sac_d2_{parent}', 'config.yaml')))
    c['obs'] = {'obstacle_velocity': True, 'control_point_geometry': True, 'clip_distance': 1.2}
    c['obstacle']['count_range'] = [1, 3]
    c['randomization']['cp_geometry'] = True
    c['randomization'].setdefault('obs_noise', {})['cp_normal_std'] = 0.05
    if arm == 's':
        c['reward'].update(obs_shaping='penalty', w_obs_margin=1.0,
                           obs_soft_margin=round(float(c['cbf']['d_safe']) + 0.02, 4))
    c['rl'].update(seed=int(seed), total_timesteps=2_000_000)
    return c


if __name__ == '__main__':
    for arm, (s0, note) in ARMS.items():
        for k, parent in enumerate(PARENTS, 1):
            c = make(arm, parent, s0 + k)
            p = os.path.join(SIM, f'config_e2_{arm}_{parent}.yaml')
            with open(p, 'w') as f:
                f.write(f'# e2_{arm}_{parent} — generated by runs/eval_all/e2/mk_e2.py from '
                        f'models/sac_d2_{parent}/config.yaml (2026-10-20).\n'
                        f'# {note}; parent d2_{parent} final, seed {s0 + k}\n')
                yaml.safe_dump(c, f, sort_keys=False)
            print(p)
