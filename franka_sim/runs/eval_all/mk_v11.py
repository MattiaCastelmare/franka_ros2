"""Build the v11 configs (2026-09-30) from the FROZEN models/sac_v10c/config.yaml.

ft_*  : fine-tunes resumed from sac_v10c/checkpoints/sac_2500000_steps.zip (best policy, 112/92 on 140 seeds)
        + its replay buffer. All at lr 1e-4 (v10c at 3e-4 degraded after 2.5M); each adds ONE change vs ft_lr1e4.
v11   : from scratch, v10 recipe + precision bonus (does it take off earlier than v10?).
"""
import copy, yaml
base = yaml.safe_load(open('franka_sim/models/sac_v10c/config.yaml'))
FT = {('rl', 'learning_rate'): 1e-4}
PREC = {('reward', 'w_prec'): 2.0, ('reward', 'prec_scale'): 0.05}
STATIC = {('obstacle', 'static_fraction'): 0.75}
OBSPOT = {('reward', 'w_obs_margin'): 2.0, ('reward', 'obs_soft_margin'): 0.30,
          ('reward', 'obs_shaping'): 'potential'}
variants = {
    'v11_ft_lr1e4':    ({**FT, ('rl', 'seed'): 11}, 'lr 1e-4 (new fine-tune baseline)'),
    'v11_ft_lr1e4_s2': ({**FT, ('rl', 'seed'): 12}, 'lr 1e-4, replicate seed (training noise)'),
    'v11_ft_prec':     ({**FT, **PREC, ('rl', 'seed'): 13}, '+ precision bonus w_prec 2 / 5 cm'),
    'v11_ft_static':   ({**FT, **STATIC, ('rl', 'seed'): 14}, '+ static_fraction 0.75'),
    'v11_ft_obspot':   ({**FT, **OBSPOT, ('rl', 'seed'): 15}, '+ potential obstacle shaping (w 2, 0.30 m)'),
    'v11_ft_combo':    ({**FT, **PREC, **STATIC, ('rl', 'seed'): 16}, '+ precision + static 0.75'),
    'v11_ft_utd2':     ({**FT, ('rl', 'gradient_steps'): 2, ('rl', 'seed'): 17}, '+ gradient_steps 2'),
    'v11_scratch_prec': ({**PREC, ('rl', 'seed'): 3}, 'FROM SCRATCH, v10 recipe + precision bonus'),
}
for name, (over, what) in variants.items():
    c = copy.deepcopy(base)
    for (sec, key), v in over.items():
        c.setdefault(sec, {})[key] = v
    with open(f'franka_sim/config_{name}.yaml', 'w') as f:
        f.write(f'# sac_{name} — generated by runs/eval_all/mk_v11.py from models/sac_v10c/config.yaml (2026-09-30).\n'
                f'# Variant: {what}\n')
        yaml.safe_dump(c, f, sort_keys=False)
    print('wrote', f'config_{name}.yaml')
