"""d3 batch (2026-10-13): shield-in-the-loop fine-tune of the d2 networks (CBF-RL style).

d2 result (runs/eval_all/d2): the 12-net ensemble is 795/800 clean ALONE, but behind the full
shield (the deployed stack) the 20-net mix scores 750 — 43 static failures, of which constrained
IK (envs/target_feasibility.py) finds a holding pose with every sphere at d >= d_safe for 36, and
the same policy alone holds 35 of those. The policy approaches in a way the shield blocks and
parks on the d_safe shell. None of the d1/d2 nets ever saw the shield in training.

Lever, from CBF-RL (Yang, Werner, de Sa, Ames, ICRA 2026, arXiv 2510.14959): train WITH the
filter in the loop and charge its corrections, r -= w (1 - exp(-(c/sigma)^2)) with
c = ||qdd_safe - clip(qdd_nom, box)|| (reward.w_correction, envs/franka_cbf_env.correction_cost).
In their ablation the filter alone in training gives a policy that only works with the filter;
filter + correction reward also works without it. Measured on d2 nets behind the shield: the
correction is non-zero on 63-69 % of static steps, median 3-4 rad/s^2 (slew limit, velocity and
position brakes, obstacle rows), so the term also smooths the policy (cf. CAPS, ICRA 2021).
With SAC's exploration noise it is ~6 rad/s^2 on 96 % of training steps (smoke run), so sigma is 5,
not 2: at 2 the cost saturates on nearly every step and carries no gradient.

Every run: parent = a d2 network at +2.0M (sac_6000000 / sac_7000000), FRESH replay buffer filled by
--policy-warmup 50k with the parent's own behaviour behind the shield, +2.0M steps, d2 reward
(w_prec 2), d1 randomisation, constraints as terminations, task.target_ik_check on (the 7-in-400
static targets no pose can hold are not drawn), eval_freq 50k.

  D    shield + w_correction 0.5                    p_s5 p_p2 b_2 p4_p1 p_s1 c_p1   seeds 301-306
  D1   shield + w_correction 1.0 (step cost 3)      p4_s1 p_s3                      seeds 311-312
  F    shield only (control: filter, no new term)   b_1 p_s2                        seeds 321-322
  M    D, obstacle rows on in half the episodes     c_s1 p_p1                       seeds 331-332

    cd franka_sim && python3 runs/eval_all/d3/mk_d3.py      → config_d3_*.yaml
"""
import copy
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
base = yaml.safe_load(open(os.path.join(SIM, 'config_d2_p_s1.yaml')))

# name: (parent d2 run, seed, w_correction, obstacle-rows probability, note)
RUNS = {
    'd_s5': ('p_s5', 301, 0.5, None, 'D: d2 p_s5 + shield + w_correction 0.5'),
    'd_p2': ('p_p2', 302, 0.5, None, 'D: d2 p_p2 + shield + w_correction 0.5'),
    'd_b2': ('b_2', 303, 0.5, None, 'D: d2 b_2 + shield + w_correction 0.5'),
    'd_p4p1': ('p4_p1', 304, 0.5, None, 'D: d2 p4_p1 + shield + w_correction 0.5'),
    'd_s1': ('p_s1', 305, 0.5, None, 'D: d2 p_s1 + shield + w_correction 0.5'),
    'd_cp1': ('c_p1', 306, 0.5, None, 'D: d2 c_p1 + shield + w_correction 0.5'),
    'd1_p4s1': ('p4_s1', 311, 1.0, None, 'D1: d2 p4_s1 + shield + w_correction 1.0'),
    'd1_s3': ('p_s3', 312, 1.0, None, 'D1: d2 p_s3 + shield + w_correction 1.0'),
    'f_b1': ('b_1', 321, 0.0, None, 'F: d2 b_1 + shield only (control)'),
    'f_s2': ('p_s2', 322, 0.0, None, 'F: d2 p_s2 + shield only (control)'),
    'm_cs1': ('c_s1', 331, 0.5, 0.5, 'M: d2 c_s1 + shield (obstacle rows 50 %) + w_correction 0.5'),
    'm_p1': ('p_p1', 332, 0.5, 0.5, 'M: d2 p_p1 + shield (obstacle rows 50 %) + w_correction 0.5'),
}

if __name__ == '__main__':
    for name, (parent, seed, w_corr, p_on, note) in RUNS.items():
        c = copy.deepcopy(base)
        c['env']['shield'] = True
        c['env']['cbf_obstacle_enabled'] = True
        if p_on is not None:
            c['env']['cbf_obstacle_on_prob'] = p_on
        c['task']['target_ik_check'] = True
        if w_corr:
            c['reward']['w_correction'] = w_corr
            c['reward']['correction_sigma'] = 5.0
        if w_corr >= 1.0:
            # keep "ending the episode early is never cheaper" (collision_step_cost >= worst per-step cost)
            c['reward']['collision_step_cost'] = 3.0
        c['rl']['seed'] = seed
        c['rl']['eval_freq'] = 50_000
        p = os.path.join(SIM, f'config_d3_{name}.yaml')
        with open(p, 'w') as f:
            f.write(f'# d3_{name} — generated by runs/eval_all/d3/mk_d3.py from config_d2_p_s1.yaml (2026-10-13).\n'
                    f'# {note}, seed {seed}, parent sac_d2_{parent}\n')
            yaml.safe_dump(c, f, sort_keys=False)
        print(p)
