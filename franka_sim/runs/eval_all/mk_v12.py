"""Build the v12 configs (2026-10-01) from the FROZEN models/sac_v11_ft_prec/config.yaml (lr 1e-4, w_prec 2).

What v11 taught: lr 1e-4 + w_prec is the best recipe; action ensembles of different seeds add ~+10 points
(policy inconsistency is the main loss); static_fraction 0.75 (ft_static/ft_combo) broke the moving case;
obstacle potential shaping and gradient_steps 2 were worse; ~35-45 % of episodes dip below d_safe.
prec_s2/s3 : ft_prec replicas from sac_v10c 2.5M (+ v10c buffer, relabelled) -> ensemble members + replication
cont       : resume ft_prec 3.75M, nothing changed (control for the next four; no buffer -> policy warm-up)
hard       : + targeted curriculum (30 % low targets z<=0.35 with a blocking obstacle) instead of static_fraction
slack      : + w_slack 0.5 -> 2.0 (fewer dips below d_safe)
hard_slack : both
lr3e5      : learning rate 3e-5 (polish, less drift between checkpoints)
prec4      : w_prec 2 -> 4
"""
import copy, yaml
base = yaml.safe_load(open('franka_sim/models/sac_v11_ft_prec/config.yaml'))
HARD = {('task', 'hard_fraction'): 0.3, ('task', 'hard_target_z_max'): 0.35}
SLACK = {('reward', 'w_slack'): 2.0}
variants = {
    'v12_prec_s2':    ({('rl', 'seed'): 21}, 'ft_prec replica, seed 21'),
    'v12_prec_s3':    ({('rl', 'seed'): 22}, 'ft_prec replica, seed 22'),
    'v12_cont':       ({('rl', 'seed'): 23}, 'continue ft_prec 3.75M unchanged (control)'),
    'v12_hard':       ({**HARD, ('rl', 'seed'): 24}, '+ hard curriculum 30 % low blocked targets'),
    'v12_slack':      ({**SLACK, ('rl', 'seed'): 25}, '+ w_slack 2.0'),
    'v12_hard_slack': ({**HARD, **SLACK, ('rl', 'seed'): 26}, '+ hard curriculum + w_slack 2.0'),
    'v12_lr3e5':      ({('rl', 'learning_rate'): 3e-5, ('rl', 'seed'): 27}, 'learning rate 3e-5'),
    'v12_prec4':      ({('reward', 'w_prec'): 4.0, ('rl', 'seed'): 28}, 'w_prec 4.0'),
}
for name, (over, what) in variants.items():
    c = copy.deepcopy(base)
    for (sec, key), v in over.items():
        c.setdefault(sec, {})[key] = v
    with open(f'franka_sim/config_{name}.yaml', 'w') as f:
        f.write(f'# sac_{name} — generated by runs/eval_all/mk_v12.py from models/sac_v11_ft_prec/config.yaml (2026-10-01).\n'
                f'# Variant: {what}\n')
        yaml.safe_dump(c, f, sort_keys=False)
    print('wrote', f'config_{name}.yaml')
