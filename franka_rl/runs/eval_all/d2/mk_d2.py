"""d2 batch (2026-10-12): continue the d1 policy-alone fine-tunes against the hold drift.

d1 result (runs/eval_all/d1, traces/d1): fine-tuning alone cut collisions and limit
violations, but reached-not-held rose to 46-110 per 400 episodes (big11: 2-3). Those
episodes reach the target and settle at a median 6-7 cm (tol 5 cm) with the same
obstacle distance, sigma_min and self-gap as held ones, so it is the single network's
bias at the target, not constraint pressure. Levers: a steep precision bonus near the
target (w_prec, as in the prec parents; d1 had it at 0) and more diverse members for an
ensemble (big11's own drift fix).

Every run: d1 settings (policy alone + clip, constraints as terminations, randomisation
on), resumed with its replay buffer, +2.0M steps, eval_freq 50k (best_model is not used
for selection anyway: checkpoints are picked on the 800-seed eval).

  P    w_prec 2 / 5 cm   from the d1 finals s1 s5 s2 s3 (4.0M) and p1 p2 (5.0M)   seeds 201-206
  P4   w_prec 4 / 5 cm   from s1, p1 (dose)                                      seeds 211-212
  B    w_prec 2 / 5 cm   from sac_b3_ft_v10c 4.0M (big11 member, own buffer)      seeds 221-222
  C    no change         from s1, p1 (control: is it just more steps?)           seeds 231-232

    cd franka_rl && python3 runs/eval_all/d2/mk_d2.py      → config_d2_*.yaml
"""
import copy
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
base = yaml.safe_load(open(os.path.join(SIM, 'config_d1_a_s1.yaml')))

# name: (seed, w_prec, note) — the parent of each run is set in launch_d2.sh
RUNS = {
    'p_s1': (201, 2.0, 'P: d1_a_s1 4.0M + w_prec 2'),
    'p_s5': (202, 2.0, 'P: d1_a_s5 4.0M + w_prec 2'),
    'p_s2': (203, 2.0, 'P: d1_a_s2 4.0M + w_prec 2'),
    'p_s3': (204, 2.0, 'P: d1_a_s3 4.0M + w_prec 2'),
    'p_p1': (205, 2.0, 'P: d1_a_p1 5.0M + w_prec 2'),
    'p_p2': (206, 2.0, 'P: d1_a_p2 5.0M + w_prec 2'),
    'p4_s1': (211, 4.0, 'P4: d1_a_s1 4.0M + w_prec 4'),
    'p4_p1': (212, 4.0, 'P4: d1_a_p1 5.0M + w_prec 4'),
    'b_1': (221, 2.0, 'B: sac_b3_ft_v10c 4.0M + d1 settings + w_prec 2'),
    'b_2': (222, 2.0, 'B: sac_b3_ft_v10c 4.0M + d1 settings + w_prec 2'),
    'c_s1': (231, 0.0, 'C: d1_a_s1 4.0M, unchanged (control)'),
    'c_p1': (232, 0.0, 'C: d1_a_p1 5.0M, unchanged (control)'),
}

for name, (seed, w_prec, note) in RUNS.items():
    c = copy.deepcopy(base)
    c['rl']['seed'] = seed
    c['rl']['eval_freq'] = 50_000
    if w_prec:
        c['reward']['w_prec'] = w_prec
        c['reward']['prec_scale'] = 0.05
    p = os.path.join(SIM, f'config_d2_{name}.yaml')
    with open(p, 'w') as f:
        f.write(f'# d2_{name} — generated by runs/eval_all/d2/mk_d2.py from config_d1_a_s1.yaml (2026-10-12).\n'
                f'# {note}, seed {seed}\n')
        yaml.safe_dump(c, f, sort_keys=False)
    print(p)
