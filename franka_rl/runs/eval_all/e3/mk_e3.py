"""e3 batch (2026-10-21): dose-response on the d_safe penalty, continuing all 12 e2 finals.

e2 result (runs/eval_all/e2/auto_eval.log, fresh seeds 5000:400): the 51-D grafts tie their 24-D parents
alone (ens_e2_gs12 797 one / 794 multi vs ens_d2top6 794 / 788) but LOSE behind the shield (706 vs 738 one,
p 1e-6; 677 vs 688 multi). Fine-tuning alone made static targets 400/400 alone by approaching closer, which
the shield then blocks. Arm S (per-step penalty below d_safe + 2 cm, w 1) beat G behind the shield in the
ensembles (+13 one, +14 multi held-out) but did not move the clearance where it matters: 69 % of static
episodes still dip below d_safe alone (parent 69 %); only the < 10 cm fraction fell (46 → 33 %).

e3 = the same penalty at w 4 (obs_shaping penalty, margin 0.17), +1.5M steps from each e2 final (G and S,
own 51-D buffers, rewards relabelled from the e2 config). Worst per-step cost ≈ 1 (dist) + 4 → collision_step_cost
5, so ending an episode by a crash or a violation never pays (the buffer's terminal transitions keep their old
step cost 2: not obs-derivable, a minority, overwritten within the run). Holding the target still pays
(+5 success + w_prec vs at most 2.8 for a hold at 5 cm), so reachable-only-close targets stay worth reaching.

    cd franka_rl && python3 runs/eval_all/e3/mk_e3.py      → config_e3_*.yaml
"""
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
PARENTS = ['p_s5', 'p4_s1', 'p_p2', 'b_1', 'b_2', 'p4_p1']
RUNS = [f'{a}_{p}' for a in ('g', 's') for p in PARENTS]

if __name__ == '__main__':
    for k, r in enumerate(RUNS, 1):
        c = yaml.safe_load(open(os.path.join(SIM, 'models', f'sac_e2_{r}', 'config.yaml')))
        c['reward'].update(obs_shaping='penalty', w_obs_margin=4.0,
                           obs_soft_margin=round(float(c['cbf']['d_safe']) + 0.02, 4),
                           collision_step_cost=5.0)
        c['rl'].update(seed=520 + k, total_timesteps=1_500_000)
        p = os.path.join(SIM, f'config_e3_{r}.yaml')
        with open(p, 'w') as f:
            f.write(f'# e3_{r} — generated by runs/eval_all/e3/mk_e3.py from models/sac_e2_{r}/config.yaml '
                    f'(2026-10-21).\n# e2_{r} final + d_safe penalty w 4 (margin 0.17), collision_step_cost 5, '
                    f'seed {520 + k}\n')
            yaml.safe_dump(c, f, sort_keys=False)
        print(p)
