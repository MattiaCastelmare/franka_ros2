"""ArmKalmanFilter: consistency, gate, per-measurement covariance, exposed covariances.

Pure numpy: the filter is a library with no ROS dependency.
"""

import numpy as np
import pytest

from franka_experiments.utils.arm_kf import ArmKalmanFilter
from franka_experiments.utils.human_utils import ray_covariance

DT = 1.0 / 30.0


def _dwna_truth(n, sigma_a, rng):
    """Positions of four keypoints following the filter's own DWNA model exactly."""
    p = np.zeros((4, 3))
    v = np.zeros((4, 3))
    out = np.empty((n, 4, 3))
    for k in range(n):
        a = rng.normal(0.0, sigma_a, size=(4, 3))
        p = p + v * DT + 0.5 * a * DT**2
        v = v + a * DT
        out[k] = p
    return out


def test_nis_is_chi2_3_when_the_model_matches():
    """Mean NIS ~ 3 for data generated by the filter's model: the scale of P is right."""
    rng = np.random.default_rng(0)
    sigma_a, sigma_m = 3.0, 0.03
    truth = _dwna_truth(4000, sigma_a, rng)
    kf = ArmKalmanFilter(dt=DT, process_accel_std=sigma_a, measurement_std=sigma_m,
                         mahalanobis_threshold=0.0)
    nis = []
    for k, p in enumerate(truth):
        kf.step(p + rng.normal(0.0, sigma_m, size=p.shape), np.ones(4), np.ones(4), dt=DT)
        if k > 100:   # past the initial transient
            nis.extend(kf.get_consistency()[0])
    assert abs(np.mean(nis) - 3.0) < 0.3


def test_gate_rejects_an_outlier_and_keeps_the_prediction():
    kf = ArmKalmanFilter(dt=DT, process_accel_std=3.0, measurement_std=0.03)
    p = np.zeros((4, 3))
    for _ in range(30):
        kf.step(p, np.ones(4), np.ones(4), dt=DT)
    outlier = p.copy()
    outlier[3] = [0.5, 0.0, 0.0]   # a depth jump, as seen in the logged raw states
    est_pos, _, measured = kf.step(outlier, np.ones(4), np.ones(4), dt=DT)
    nis, gated = kf.get_consistency()
    assert gated[3] and not measured[3]
    assert nis[3] > kf.mahalanobis_threshold
    assert np.linalg.norm(est_pos[3]) < 0.01
    assert not gated[:3].any() and measured[:3].all()


def test_no_measurement_means_no_nis():
    kf = ArmKalmanFilter(dt=DT)
    kf.step(np.zeros((4, 3)), np.ones(4), np.ones(4), dt=DT)
    kf.step(np.full((4, 3), np.nan), np.zeros(4), np.zeros(4), dt=DT)
    nis, gated = kf.get_consistency()
    assert np.isnan(nis).all() and not gated.any()


def test_ray_covariance_admits_a_depth_error_the_default_rejects():
    """A borrowed depth is wrong along the camera ray only: shaped R accepts it, isotropic R gates it."""
    ray = np.array([1.0, 0.0, 0.0])
    measurement = np.zeros((4, 3))
    measurement[2] = 0.15 * ray   # 15 cm along the ray, inside the +-0.20 m fallback band

    def settle():
        kf = ArmKalmanFilter(dt=DT, process_accel_std=3.0, measurement_std=0.03)
        for _ in range(30):
            kf.step(np.zeros((4, 3)), np.ones(4), np.ones(4), dt=DT)
        return kf

    default = settle()
    default.step(measurement, np.ones(4), np.ones(4), dt=DT)
    assert default.get_consistency()[1][2]

    shaped = settle()
    covs = np.full((4, 3, 3), np.nan)
    covs[2] = ray_covariance(ray, 0.03, 0.12)
    pos, _, measured = shaped.step(measurement, np.ones(4), np.ones(4), dt=DT,
                                   measurement_covariances=covs)
    assert measured[2]
    # Weak along the ray: the estimate moves only a little toward the measurement
    assert 0.0 < pos[2, 0] < 0.05


def test_ray_covariance_shape():
    ray = np.array([0.3, -0.4, 1.2])
    R = ray_covariance(ray, 0.03, 0.12)
    r = ray / np.linalg.norm(ray)
    assert np.allclose(R, R.T)
    assert r @ R @ r == pytest.approx(0.12**2)
    perp = np.cross(r, [1.0, 0.0, 0.0])
    perp /= np.linalg.norm(perp)
    assert perp @ R @ perp == pytest.approx(0.03**2)


def test_first_measurement_with_custom_covariance_widens_the_prior():
    kf = ArmKalmanFilter(dt=DT, initial_position_std=0.05)
    covs = np.full((4, 3, 3), np.nan)
    covs[0] = ray_covariance([0.0, 0.0, 1.0], 0.03, 0.12)
    kf.step(np.zeros((4, 3)), np.ones(4), np.ones(4), dt=DT, measurement_covariances=covs)
    P_pp, _, _ = kf.get_covariances()
    assert P_pp[0, 2, 2] == pytest.approx(0.05**2 + 0.12**2)
    assert P_pp[1, 2, 2] == pytest.approx(0.05**2)
    assert np.all(np.linalg.eigvalsh(P_pp[0]) > 0.0)


def test_update_count_counts_accepted_measurements_only():
    kf = ArmKalmanFilter(dt=DT)
    p = np.zeros((4, 3))
    for _ in range(5):
        kf.step(p, np.ones(4), np.ones(4), dt=DT)
    kf.step(np.full((4, 3), np.nan), np.zeros(4), np.zeros(4), dt=DT)   # coasting
    assert kf.update_count.tolist() == [5, 5, 5, 5]
    kf.reset(1)
    assert kf.update_count.tolist() == [5, 0, 5, 5]


def test_covariances_are_symmetric_and_nan_when_uninitialized():
    kf = ArmKalmanFilter(dt=DT)
    p = np.full((4, 3), np.nan)
    p[0] = [0.1, 0.2, 0.3]
    for _ in range(10):
        kf.step(p, np.ones(4), np.where(np.isfinite(p[:, 0]), 1.0, 0.0), dt=DT)
    P_pp, P_vv, P_pv = kf.get_covariances()
    assert P_pp.shape == P_vv.shape == P_pv.shape == (4, 3, 3)
    assert np.allclose(P_pp[0], P_pp[0].T) and np.allclose(P_vv[0], P_vv[0].T)
    assert np.isnan(P_pp[1:]).all() and np.isnan(P_vv[1:]).all()

MAX_LENGTHS = (0.40, 0.33, 0.20)


def _moving_arm_kf(wrist_speed):
    """A still arm (shoulder, elbow, wrist, index along x) whose wrist moves along +x."""
    kf = ArmKalmanFilter(dt=DT, process_accel_std=3.0, measurement_std=0.03)
    arm = np.array([[0.0, 0.0, 0.0], [0.30, 0.0, 0.0], [0.55, 0.0, 0.0], [0.65, 0.0, 0.0]])
    for k in range(30):
        p = arm.copy()
        p[2:, 0] += wrist_speed * k * DT
        kf.step(p, np.ones(4), np.ones(4), dt=DT)
    return kf


def test_limit_segments_pulls_a_predicted_keypoint_back_to_its_measured_neighbour():
    """An occluded wrist coasting at 1 m/s stays within the forearm length of the elbow."""
    kf = _moving_arm_kf(wrist_speed=1.0)
    p = np.full((4, 3), np.nan)
    p[:2] = kf.get_estimates()[0][:2]          # shoulder and elbow still measured
    for _ in range(9):                          # 0.3 s with no wrist and no index
        _, _, measured = kf.step(p, np.ones(4), np.where(np.isfinite(p[:, 0]), 1.0, 0.0), dt=DT)
        pos, vel = kf.limit_segments(measured, MAX_LENGTHS)
    assert np.linalg.norm(pos[2] - pos[1]) == pytest.approx(MAX_LENGTHS[1])
    assert vel[2, 0] == pytest.approx(0.0, abs=1e-9)   # no velocity left stretching the forearm
    # The index has no measured neighbour: only its own prediction
    assert np.linalg.norm(pos[3] - pos[2]) > MAX_LENGTHS[2]


def test_limit_segments_leaves_measured_and_short_segments_alone():
    kf = _moving_arm_kf(wrist_speed=0.0)
    before = kf.get_estimates()
    pos, vel = kf.limit_segments(np.ones(4, dtype=bool), MAX_LENGTHS)
    assert np.allclose(pos, before[0]) and np.allclose(vel, before[1])
    pos, vel = kf.limit_segments(np.array([True, True, False, True]), MAX_LENGTHS)
    assert np.allclose(pos, before[0]) and np.allclose(vel, before[1])
