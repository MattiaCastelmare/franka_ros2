    section_f(files, cls)
    print(f'\n--- S4: {COUNT["PASS"]} PASS, {COUNT["FAIL"]} FAIL, {COUNT["OBS"]} OBS, {COUNT["UNVERIFIED"]} UNVERIFIED ---')
    return 1 if COUNT['FAIL'] else 0


