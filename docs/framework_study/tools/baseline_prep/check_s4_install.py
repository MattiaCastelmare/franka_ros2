GEN_DIRS = ('rosidl_adapter', 'rosidl_generator_c', 'rosidl_generator_cpp', 'rosidl_generator_py',
            'rosidl_typesupport_c', 'rosidl_typesupport_cpp', 'rosidl_typesupport_fastrtps_c',
            'rosidl_typesupport_fastrtps_cpp', 'rosidl_typesupport_introspection_c',
            'rosidl_typesupport_introspection_cpp')
GEN_EXT = ('.idl', '.h', '.hpp', '.c', '.cpp', '.py')


def nm_defined(path):
    r = run('nm', '-D', '--defined-only', path)
    return {ln.split()[-1] for ln in r.stdout.decode().splitlines() if ln.strip()}


MSG_PROBE = r'''
import json, importlib, sys
res = {}
for t in sys.argv[1:]:
    mod, cls = t.rsplit('.', 1)
    c = getattr(importlib.import_module(mod), cls)
    res[t] = [importlib.import_module(mod).__file__, list(c.get_fields_and_field_types().items())]
print(json.dumps(res))
'''


def section_d(work):
    section('D. franka_msgs: regenerated interfaces vs the S1 archive')
    old = {}
    olib = {}
    os.makedirs(os.path.join(work, 'old_msgs'), exist_ok=True)
    with tarfile.open(os.path.join(S1, 'container', 'ros2_ws_build.tar'), 'r|') as tf:
        for m in tf:
            n = m.name
            if not n.startswith('build/franka_msgs/') or not m.isfile():
                continue
            rel = n[len('build/franka_msgs/'):]
            if rel.split('/')[0] in GEN_DIRS and rel.endswith(GEN_EXT):
                old[rel] = tf.extractfile(m).read()
            elif re.match(r'libfranka_msgs__[^/]+\.so$', os.path.basename(rel)) and \
                    os.path.basename(rel) not in olib:
                rel = os.path.basename(rel)
                p = os.path.join(work, 'old_msgs', rel)
                open(p, 'wb').write(tf.extractfile(m).read())
                olib[rel] = p
    newt = ctar('/ros2_ws/build/franka_msgs', [d for d in GEN_DIRS])
    new = {m.name: newt.extractfile(m).read() for m in newt.getmembers()
           if m.isfile() and m.name.endswith(GEN_EXT)}
    only_old, only_new = sorted(set(old) - set(new)), sorted(set(new) - set(old))
    diff = sorted(k for k in set(old) & set(new) if old[k] != new[k])
    out('INFO', f'generated sources: S1 {len(old)}, new {len(new)}; only in S1 {len(only_old)}, only new '
        f'{len(only_new)}, differing {len(diff)}')
    for k in only_old + only_new + diff:
        out('INFO', f'  {"only S1" if k in only_old else "only new" if k in only_new else "differs"}: {k}')
    struct = [k for k in set(old) & set(new) if re.search(r'__struct\.hp?p?$|\.idl$', k)]
    out('PASS' if not (only_old or only_new or diff) else 'FAIL',
        f'every generated rosidl source (IDL, C/C++ structs, type supports, Python) is byte-identical to S1 '
        f'({len(struct)} IDL/struct headers among them)')
    os.makedirs(os.path.join(work, 'new_msgs'), exist_ok=True)
    lt = ctar('/ros2_ws/install/franka_msgs/lib', ['.'])
    nlib = {}
    for m in lt.getmembers():
        if m.isfile() and m.name.endswith('.so'):
            p = os.path.join(work, 'new_msgs', os.path.basename(m.name))
            open(p, 'wb').write(lt.extractfile(m).read())
            nlib[os.path.basename(m.name)] = p
    same = True
    for k in sorted(set(olib) | set(nlib)):
        if k not in olib or k not in nlib:
            same = False
            out('INFO', f'  library only in {"S1" if k in olib else "new"}: {k}')
            continue
        a, b = nm_defined(olib[k]), nm_defined(nlib[k])
        if a != b:
            same = False
            out('INFO', f'  {k}: exported symbols differ (-{len(a - b)} +{len(b - a)})')
    out('PASS' if same else 'FAIL', f'the {len(nlib)} franka_msgs libraries export exactly the S1 symbol sets')
    # non-rebuilt linkers
    defined = set().union(*(nm_defined(p) for p in nlib.values()))
    allok = True
    for pkg in NOT_REBUILT_LINKERS:
        r = dsh(f'for f in $(find /ros2_ws/install/{pkg} -name "*.so" -type f -o -name "*.so" -type l); do '
                f'echo "@@$f"; ldd $f | grep -E "franka_msgs|not found"; echo "%%"; '
                f'nm -D --undefined-only $f | grep franka_msgs | awk "{{print \\$NF}}"; done')
        for blk in r.stdout.decode().split('@@')[1:]:
            head, rest = blk.split('\n', 1)
            ldd_part, und = rest.split('%%', 1)
            und = {s for s in und.split() if s}
            missing = und - defined
            nf = 'not found' in ldd_part
            paths = sorted({ln.split('=>')[1].split('(')[0].strip() for ln in ldd_part.splitlines() if '=>' in ln})
            wrong = [p for p in paths if p and not p.startswith('/ros2_ws/install/franka_msgs/lib/')]
            ok = not missing and not nf and not wrong
            allok &= ok
            out('INFO' if ok else 'FAIL', f'{pkg}: {os.path.basename(head)}: {len(paths)} franka_msgs libs from '
                f'install/franka_msgs; {len(und)} undefined franka_msgs symbols, {len(missing)} unresolved'
                + (f'; WRONG {wrong}' if wrong else '') + ('; NOT FOUND' if nf else ''))
    out('PASS' if allok else 'FAIL', 'the four non-rebuilt linkers resolve every franka_msgs symbol they use '
        'against the new libraries (link level)')
    # Python types used by the in-scope code
    used = set()
    for d in ('franka_experiments', 'franka_simulation_experiments', 'franka_simulation'):
        g_ = run('git', '-C', REPO, 'grep', '-h', '-E', r'from franka_msgs\.(msg|srv|action) import', BASE, '--', d)
        for ln in g_.stdout.decode().splitlines():
            g = re.search(r'from (franka_msgs\.\w+) import \(?([\w, ]+)', ln.split(':', 2)[-1])
            if g:
                used |= {f'{g.group(1)}.{c.strip()}' for c in g.group(2).split(',') if c.strip()}
    r = dsh('python3 -B - ' + ' '.join(sorted(used)), inp=MSG_PROBE.encode())
    if r.returncode:
        out('FAIL', f'importing the used franka_msgs types failed: {r.stderr.decode()[-300:]}')
        return
    res = json.loads(r.stdout)
    tok = True
    for t, (f, fields) in sorted(res.items()):
        kind, name = t.split('.')[1], t.split('.')[2]
        src = run('git', '-C', REPO, 'cat-file', 'blob', f'{BASE}:franka_msgs/{kind}/{name}.{kind}').stdout.decode()
        mf = []
        for line in src.split('---')[0].splitlines():
            line = line.split('#')[0].strip()
            tk = line.split()
            if len(tk) >= 2 and '=' not in tk[1] and not re.match(r'^[A-Z0-9_]+$', tk[1]):
                mf.append(tk[1])
        names = [k for k, _ in fields]
        ok = names == mf and f.startswith('/ros2_ws/install/franka_msgs/')
        tok &= ok
        out('INFO' if ok else 'FAIL', f'{t}: {len(names)} fields, order equal to the baseline .{kind}: {names == mf}; '
            f'module {f}')
    out('PASS' if tok else 'FAIL', f'the {len(res)} franka_msgs types imported by the in-scope Python load from the '
        'new install and have the baseline fields in the baseline order')


