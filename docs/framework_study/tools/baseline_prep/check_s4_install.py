PYC_PROBE = r'''
import importlib.util, os, sys, json
res = []
for root in sys.argv[1:]:
    for dp, dn, fn in os.walk(root):
        for f in fn:
            if not f.endswith('.pyc'):
                continue
            p = os.path.join(dp, f)
            tag = f.split('.')[-2]
            src = os.path.join(os.path.dirname(dp), f.split('.')[0] + '.py') if os.path.basename(dp) == '__pycache__' else None
            h = open(p, 'rb').read(16)
            flags = int.from_bytes(h[4:8], 'little')
            st = os.stat(src) if src and os.path.exists(src) else None
            valid = None
            if tag == sys.implementation.cache_tag and h[:4] == importlib.util.MAGIC_NUMBER and st and flags == 0:
                valid = (int.from_bytes(h[8:12], 'little') == (int(st.st_mtime) & 0xFFFFFFFF)
                         and int.from_bytes(h[12:16], 'little') == (st.st_size & 0xFFFFFFFF))
            res.append([p, tag, flags, src if st else None, valid, os.stat(p).st_mtime])
print(json.dumps(res))
'''


def section_b(cls):
    section('B. .pyc files in the six packages')
    roots = [f'/ros2_ws/install/{p}' for p in SIX]
    r = dsh('python3 -B - ' + ' '.join(roots), inp=PYC_PROBE.encode())
    res = json.loads(r.stdout or b'[]')
    copied = {f'/ros2_ws/install/{n}' for n, _, _ in cls['untracked-copy']}
    by = collections.Counter()
    for p, tag, flags, src, valid, mt in res:
        origin = 'copied from the source tree' if p in copied else (
            'compiled by the S3 build' if WIN[0] <= mt <= WIN[1] else 'OTHER')
        by[(origin, tag)] += 1
        if origin == 'OTHER':
            out('FAIL', f'{p}: .pyc of unknown origin (mtime {utc(mt)})')
        if origin.startswith('copied') and tag == 'cpython-310':
            out('OBS', f'{p}: cpython-310 cache copied from the source tree; header matches the installed '
                f'{os.path.basename(src) if src else "(no .py)"}: {valid} -> CPython 3.10 '
                f'{"WOULD load this bytecode" if valid else "ignores it (recompiles in memory)"}')
    usable = [p for p, tag, flags, src, valid, mt in res if valid and p in copied]
    if usable:
        r = dsh('python3 -B - ' + ' '.join(usable), inp=PYC_EQUIV.encode())
        for ln in r.stdout.decode().splitlines():
            p, eq = ln.rsplit(' ', 1)
            out('PASS' if eq == 'True' else 'FAIL', f'{p}: its code objects equal a fresh compile of the installed .py '
                f'(co_filename aside): {eq}')
        if r.returncode:
            out('FAIL', f'pyc equivalence probe failed: {r.stderr.decode()[-300:]}')
    for (o, t), c in sorted(by.items()):
        out('INFO', f'{c:3d} x {t:12s} {o}')
    out('INFO', 'CPython 3.10 ignores cpython-313 caches (tag mismatch); a cpython-310 cache is used only when '
        'its header records the mtime and size of the .py beside it')
    return res


PYC_EQUIV = r'''
import marshal, os, sys, types
def norm(c):
    consts = tuple(norm(k) if isinstance(k, types.CodeType) else k for k in c.co_consts)
    return c.replace(co_filename='', co_consts=consts)
for p in sys.argv[1:]:
    src = os.path.join(os.path.dirname(os.path.dirname(p)), os.path.basename(p).split('.')[0] + '.py')
    cached = marshal.loads(open(p, 'rb').read()[16:])
    fresh = compile(open(src, 'rb').read(), src, 'exec', dont_inherit=True)
    print(p, marshal.dumps(norm(cached)) == marshal.dumps(norm(fresh)))
'''


