sys.dont_write_bytecode = True
REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..'))
CT = os.environ.get('FS_CONTAINER', 'franka_ros2')
S1 = os.environ.get('FS_S1', os.path.expanduser('~/franka_baseline_evidence/baseline_f708991/00_pre_rebuild'))
WORK = os.environ.get('FS_WORKDIR') or tempfile.mkdtemp(prefix='s4_')
BASE = 'ba68077'
QUAR = '/ros2_ws/quarantine_s3_20261112'
# S3 build window (UTC, from 01_build/colcon_build_console.log: 11:14:36 -> 11:15:11), with margin.
WIN = (datetime(2026, 11, 12, 11, 14, 30, tzinfo=timezone.utc).timestamp(),
       datetime(2026, 11, 12, 11, 15, 20, tzinfo=timezone.utc).timestamp())
PKGDIR = {'franka_msgs': 'franka_msgs', 'franka_ign_ros2_control': 'franka_gazebo/franka_ign_ros2_control',
          'franka_rt_controllers': 'franka_rt_controllers', 'franka_simulation': 'franka_simulation',
          'franka_experiments': 'franka_experiments',
          'franka_simulation_experiments': 'franka_simulation_experiments'}
SIX = list(PKGDIR)
NOT_REBUILT_LINKERS = ['franka_hardware', 'franka_gripper', 'franka_robot_state_broadcaster',
                       'franka_example_controllers']
PLUGINS = [('franka_rt_controllers', 'libfranka_rt_controllers.so'),
           ('franka_rt_controllers', 'libcbf_torque_controller.so'),
           ('franka_ign_ros2_control', 'libfranka_ign_ros2_control-system.so'),
           ('franka_ign_ros2_control', 'libign_hardware_plugins.so'),
           ('franka_simulation', 'libfranka_scenario_obstacles.so')]
COUNT = collections.Counter()


def out(tag, msg):
    COUNT[tag] += 1
    print(f'{tag:10s} {msg}', flush=True)


def section(t):
    print(f'\n== {t}', flush=True)


def run(*a, inp=None, check=False):
    r = subprocess.run(a, capture_output=True, input=inp)
    if check and r.returncode:
        raise RuntimeError(f'{a}: {r.stderr.decode()[:400]}')
    return r


def dsh(cmd, cwd='/tmp', inp=None, source=True):
    """bash in the container; the install is sourced unless source=False. Never writes bytecode."""
    pre = 'source /ros2_ws/install/setup.bash >/dev/null 2>&1; ' if source else ''
    return run('docker', 'exec', '-i', '-w', cwd, '-e', 'PYTHONDONTWRITEBYTECODE=1', CT, 'bash', '-c', pre + cmd,
               inp=inp)


def git(*a):
    return run('git', '-C', REPO, *a, check=True).stdout.decode()


def blob_sha(data):
    return hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()


def ctar(root, names):
    r = run('docker', 'exec', CT, 'tar', '-C', root, '-cf', '-', *names, check=True)
    return tarfile.open(fileobj=io.BytesIO(r.stdout))


def utc(ts):
    return datetime.fromtimestamp(ts, timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')


# ---------------------------------------------------------------------------------------------- A
GENERATED = [r'\.so(\.\d+)*$', r'^share/ament_index/', r'^share/colcon-core/', r'^share/[^/]+/(hook|environment)/',
             r'^share/[^/]+/(local_setup|package)\.(sh|bash|zsh|ps1|dsv)$', r'^share/[^/]+/cmake/',
             r'\.egg-info(/|$)', r'\.egg-link$', r'\.pth$', r'^include/[^/]+/[^/]+/(msg|srv|action)/',
             r'^share/[^/]+/(msg|srv|action)/[^/]+\.idl$', r'^local/lib/python3\.10/dist-packages/',
             r'^share/[^/]+/rust/', r'^share/[^/]+/(srv|action)/[^/]+_(Request|Response|Goal|Result|Feedback)\.msg$',
             r'^lib/franka_experiments/[^/]+$']


def candidates(pkg, rel):
    d, q = PKGDIR[pkg], rel.split('/')
    c = []
    if q[0] == 'share' and len(q) > 2 and q[1] == pkg:
        c.append(f'{d}/' + '/'.join(q[2:]))
    if q[0] == 'lib' and len(q) > 2 and q[1] == pkg:
        r_ = '/'.join(q[2:])
        c += [f'{d}/scripts/{r_}.py', f'{d}/scripts/{r_}', f'{d}/{r_}']
    if 'site-packages' in q or 'dist-packages' in q:
        i = q.index('site-packages' if 'site-packages' in q else 'dist-packages')
        c.append(f'{d}/' + '/'.join(q[i + 1:]))
    if q[0] == 'include':
        c += [f'{d}/' + '/'.join(q), f'{d}/include/' + '/'.join(q[2:])]
    return c


def underlay_templates():
    r = dsh('find /opt/ros/humble/share -path "*/environment/*" -type f -exec sha1sum {} + 2>/dev/null', source=False)
    return {ln.split()[0] for ln in r.stdout.decode().splitlines() if ln.strip()}


def section_a(inst):
    section(f'A. installed files of the six packages vs {BASE} (content)')
    templ = underlay_templates()
    files = {}
    for m in inst.getmembers():
        if m.isfile():
            files[m.name] = (inst.extractfile(m).read(), m.mtime)
        elif not m.isdir():
            out('FAIL', f'non-regular install entry (symlink or special): {m.name} -> {m.linkname}')
    tracked = {}
    for pkg, d in PKGDIR.items():
        idx = collections.defaultdict(list)
        for line in git('ls-tree', '-r', '--full-tree', BASE, '--', d).splitlines():
            meta, path = line.split('\t', 1)
            idx[meta.split()[2]].append(path)
        tracked[pkg] = idx
    cls = collections.defaultdict(list)
    kinds = collections.Counter()
    installed_blobs = collections.defaultdict(set)
    for name, (data, mtime) in sorted(files.items()):
        pkg, rel = name.split('/', 1)
        sha = blob_sha(data)
        installed_blobs[pkg].add(sha)
        cands = candidates(pkg, rel)
        tracked_paths = {p for paths in tracked[pkg].values() for p in paths}
        if sha in tracked[pkg]:
            srcs = tracked[pkg][sha]
            same_name = any(os.path.basename(s) in (os.path.basename(rel), os.path.basename(rel) + '.py') for s in srcs)
            cls['tracked'].append(name)
            ext = ('.launch.py' if rel.endswith('.launch.py') else os.path.splitext(rel)[1] or '(none)')
            kinds[(pkg, ext)] += 1
            if not same_name:
                out('INFO', f'{name}: equal to tracked {srcs[0]} under another name')
            continue
        bad = [c for c in cands if c in tracked_paths]
        if bad:
            cls['TRACKED-DIFFERS'].append(name)
            out('FAIL', f'{name}: differs from the tracked baseline file {bad[0]}')
            continue
        copied = [c for c in cands if os.path.isfile(os.path.join(REPO, c))
                  and blob_sha(open(os.path.join(REPO, c), 'rb').read()) == sha]
        if copied:
            cls['untracked-copy'].append((name, copied[0], mtime))
            continue
        if re.match(r'share/[^/]+/environment/', rel) and hashlib.sha1(data).hexdigest() in templ:
            cls['underlay-template'].append(name)
            continue
        if any(re.search(p, rel) for p in GENERATED):
            if WIN[0] <= mtime <= WIN[1]:
                cls['generated'].append(name)
            else:
                cls['generated-OLD'].append(name)
                out('FAIL', f'{name}: generated-type file with mtime {utc(mtime)}, outside the S3 build')
            continue
        cls['UNEXPLAINED'].append(name)
        out('FAIL', f'{name}: no tracked source, not generated, not a copy of a source-tree file')
    n = len(files)
    out('INFO', f'{n} regular files: ' + ', '.join(f'{k} {len(v)}' for k, v in sorted(cls.items())))
    for pkg in SIX:
        ks = sorted((e, c) for (p, e), c in kinds.items() if p == pkg)
        out('INFO', f'  {pkg}: byte-equal to tracked baseline files by type: ' + ', '.join(f'{e} {c}' for e, c in ks))
    ok = not cls['TRACKED-DIFFERS'] and not cls['UNEXPLAINED'] and not cls['generated-OLD']
    out('PASS' if ok else 'FAIL', 'every installed file is a byte-equal copy of a tracked baseline file, a file '
        'generated by the S3 build, or a copy of a source-tree file (next line)')
    for name, src, mtime in cls['untracked-copy']:
        out('OBS', f'untracked/ignored source-tree file copied into the install: {name} <- {src} (mtime {utc(mtime)})')
    # wrappers of the console scripts must point to franka_experiments entry points
    wr = [k for k in files if re.match(r'franka_experiments/lib/franka_experiments/[^/]+$', k)]
    ep = [k for k in files if re.match(r'franka_experiments/lib/python3\.10/site-packages/[^/]+\.egg-info/entry_points\.txt$', k)]
    eps = dict(re.findall(r'^(\w+)\s*=\s*([\w.]+:\w+)', files[ep[0]][0].decode(), flags=re.M)) if ep else {}
    setup = run('git', '-C', REPO, 'cat-file', 'blob', f'{BASE}:franka_experiments/setup.py').stdout.decode()
    seps = dict(re.findall(r"'(\w+)\s*=\s*([\w.]+:\w+)'", setup))
    bad = []
    for k in wr:
        n = os.path.basename(k)
        body = files[k][0].decode()
        mod = eps.get(n, ':').split(':')[0]
        modfile = 'franka_experiments/lib/python3.10/site-packages/' + mod.replace('.', '/') + '.py'
        if (f"'console_scripts', '{n}'" not in body or "franka-experiments==0.0.1" not in body
                or eps.get(n) != seps.get(n) or modfile not in files):
            bad.append(n)
    out('PASS' if wr and not bad and len(wr) == len(eps) == len(seps) else 'FAIL',
        f'{len(wr)} console-script wrappers: each names its own entry point; installed entry_points.txt '
        f'({len(eps)}) == setup.py console_scripts ({len(seps)}); every target module is installed'
        + (f'; BAD {bad}' if bad else ''))
    # converse: tracked files with no byte-equal installed copy (INFO; many are not installed by design)
    section('A2. tracked baseline files without a byte-equal installed copy (INFO; review the list)')
    for pkg, d in PKGDIR.items():
        miss = collections.defaultdict(list)
        for sha, paths in tracked[pkg].items():
            if sha in installed_blobs[pkg]:
                continue
            for p in paths:
                top = p[len(d) + 1:].split('/')[0]
                miss[top].append(p[len(d) + 1:])
        for top, ps in sorted(miss.items()):
            show = ', '.join(sorted(ps)[:12]) + (' …' if len(ps) > 12 else '')
            out('INFO', f'{pkg}/{top}: {len(ps)} not installed: {show}')
    return files, cls


