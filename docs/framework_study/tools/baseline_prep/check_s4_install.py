def section_f(files, cls):
    section('F. Python import resolution (F-7-5, O-9)')
    s3 = set()
    for ln in open(os.path.join(os.path.dirname(S1), '01_build', 'install_six_packages_sha256.txt')):
        s3.add('/ros2_ws/' + ln.split(None, 1)[1].strip())
    tracked = set(git('ls-files').splitlines())
    copied = {f'/ros2_ws/install/{n}' for n, _, _ in cls['untracked-copy']}
    allok = True
    for label, cwd, mode in CONTEXTS:
        r = run('docker', 'exec', '-i', '-w', cwd, '-e', 'PYTHONDONTWRITEBYTECODE=1', '-e', f'S4_MODE={mode}', CT, 'bash',
                '-c', 'source /ros2_ws/install/setup.bash >/dev/null 2>&1; python3 -B -', inp=IMPORT_PROBE.encode())
        if r.returncode:
            out('FAIL', f'[{label}] probe failed: {r.stderr.decode()[-300:]}')
            allok = False
            continue
        res = json.loads(r.stdout)
        out('INFO', f'[{label}] cwd {res["cwd"]}; sys.path[0:3] {res["sys_path"][:3]}')
        for m, o in res['spec'].items():
            where = ('SOURCE' if str(o).startswith('/ros2_ws/src/') else 'INSTALL' if str(o).startswith('/ros2_ws/install/')
                     else 'QUARANTINE' if 'quarantine' in str(o) else 'namespace' if str(o).startswith('namespace:')
                     else 'not found' if o is None else 'other')
            out('INFO', f'    {m:45s} -> {where:9s} {o}')
        roots = collections.Counter()
        bad = []
        cache_valid = cache_stale = 0
        for name, (f, valid) in res['loaded'].items():
            if f.startswith('/ros2_ws/src/'):
                rel = f[len('/ros2_ws/src/'):]
                roots['source (tracked)' if rel in tracked else 'source (UNTRACKED)'] += 1
                if rel not in tracked:
                    bad.append(f)
            elif f.startswith('/ros2_ws/install/'):
                pkg = f.split('/')[3]
                if pkg in SIX:
                    roots[f'install/{pkg}'] += 1
                    if f not in s3 or f in copied:
                        bad.append(f)
                else:
                    roots[f'install/{pkg} (not rebuilt)'] += 1
            else:
                roots['OTHER'] += 1
                bad.append(f)
            cache_valid += valid is True
            cache_stale += valid is False
        for m, e in res['errors'].items():
            out('FAIL', f'    import {m}: {e}')
        ok = not bad and not res['errors']
        allok &= ok
        out('INFO' if ok else 'FAIL', f'    imported the four pipeline node modules: {sum(roots.values())} modules from '
            f'/ros2_ws: {dict(roots)}; cached .pyc next to them: {cache_valid} valid, {cache_stale} stale (ignored)'
            + (f'; UNEXPECTED {bad[:5]}' if bad else ''))
    out('PASS' if allok else 'FAIL', 'in every context every loaded /ros2_ws module is a tracked source file or an '
        'S3-built install file (no quarantine, no untracked or copied artifact)')


def main():
    print(f'S4 install verification; repository {REPO}; container {CT}; work dir {WORK}')
    print(f'HEAD {git("rev-parse", "HEAD").strip()}; baseline {BASE}; run {datetime.now(timezone.utc):%Y-%m-%d %H:%M:%S} UTC')
