YAML_PROBE = r'''
import yaml, sys, json
def walk(o, path, acc):
    if isinstance(o, dict):
        for k, v in o.items():
            if k == 'd_safe':
                acc.append(['/'.join(path + [str(k)]), v])
            walk(v, path + [str(k)], acc)
    elif isinstance(o, list):
        for i, v in enumerate(o):
            walk(v, path + [str(i)], acc)
    return acc
r = {}
for p in sys.argv[1:]:
    d = yaml.safe_load(open(p))
    r[p] = walk(d, [], [])
print(json.dumps(r))
'''


