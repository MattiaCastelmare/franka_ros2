#!/usr/bin/env python3
"""S4 of the baseline preparation: is the rebuilt install the documented source? Read-only. Host.

Runs after the approved S3 clean build (2026-11-12). Nothing is written in the repository or in the
container: the container is only read with `docker exec … tar -cf -`, `ldd`, `nm`, `readelf`,
`strings`, and Python processes started with `-B` and PYTHONDONTWRITEBYTECODE=1 that resolve and
import modules (no ROS node is created: `rclpy.init` is never called). Extracted binaries for the
symbol comparison go to a temporary directory outside the repository (FS_WORKDIR).

Sections (tags: PASS / FAIL = unexpected failure of the new install; OBS = an unexpected artifact
that is recorded, not a failure of the build; INFO; UNVERIFIED = cannot be established statically):
  A. every regular file of the six installed packages, classified by content against the baseline
     `ba68077` (tracked file, generated by the build, copied untracked source file, unexplained);
     the converse (tracked source files without an installed copy) is listed as INFO;
  B. every `.pyc` in the six packages: which Python it targets, whether CPython 3.10 would accept it
     for the `.py` beside it (header mtime/size), and where it came from;
  C. `fr3_control.yaml`: every `d_safe` key, installed and source;
  D. `franka_msgs`: generated sources (`build/franka_msgs/rosidl_*`) against the S1 archive;
     exported symbols of the eight libraries against S1; the four non-rebuilt packages that link
     them (`ldd`, undefined `franka_msgs` symbols resolved by the new libraries); the Python types
     the in-scope code imports (fields and types against the source `.msg`);
  E. compiled plugins: build time, `ldd`, RUNPATH, CMake cache, Pinocchio version, pluginlib index
     and descriptors, registered class names in the libraries, the Gazebo system-plugin search path
     and shadowing, exported symbols against the quarantined pre-S3 libraries (INFO);
  F. Python import resolution from ten execution contexts (F-7-5, O-9).

Environment: FS_CONTAINER (default franka_ros2), FS_S1 (S1 evidence directory), FS_WORKDIR.
Usage: python3 -I -B docs/framework_study/tools/baseline_prep/check_s4_install.py
Exit code: 0 if no FAIL, 1 otherwise.
"""
